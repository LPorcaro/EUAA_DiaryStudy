def aggregate_to_construct_level(
    prob_df: pd.DataFrame,
    ci_df: pd.DataFrame,
    pb_cols: list[str],
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """
    Average item-level conditional probabilities and confidence interval bounds
    to construct level.

    Confidence interval bounds are averaged across items (conservative
    approximation).

    Parameters
    ----------
    prob_df:
        Item-level conditional probabilities
        (index = PB trigger, columns = context levels).
    ci_df:
        Item-level CI tuples, same shape as ``prob_df``.
    pb_cols:
        Ordered PB column list used to identify construct membership.

    Returns
    -------
    construct_prob_df:
        Construct-level probabilities (index = construct, columns = context).
    construct_ci_df:
        Construct-level CI tuples, same shape.
    """
    prob_rows: dict = {}
    ci_rows:   dict = {}

    for c in ("SB", "CI", "LD", "O"):
        items = [p for p in pb_cols if get_construct(p) == c]
        if not items or not all(i in prob_df.index for i in items):
            continue

        prob_rows[c] = prob_df.loc[items].mean()

        ci_lo = pd.DataFrame(
            {col: [ci_df.loc[i, col][0] for i in items] for col in ci_df.columns}
        ).mean()
        ci_hi = pd.DataFrame(
            {col: [ci_df.loc[i, col][1] for i in items] for col in ci_df.columns}
        ).mean()
        ci_rows[c] = {col: (float(ci_lo[col]), float(ci_hi[col]))
                      for col in ci_df.columns}

    construct_prob_df = pd.DataFrame(prob_rows).T
    construct_prob_df.index.name = "construct"

    construct_ci_df = pd.DataFrame(ci_rows).T
    construct_ci_df.index.name = "construct"

    return construct_prob_df, construct_ci_df


