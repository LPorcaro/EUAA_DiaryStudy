def plot_effect_size_forest(
    intent_results: pd.DataFrame,
    temp_results: pd.DataFrame,
    trigger_results: pd.DataFrame,
    pb_order: list[str],
) -> None:
    """
    Forest plot of effect sizes across all three context variables.

    INTENT and TEMP panels show rank-biserial r (range -1 to +1) with a
    dashed reference line at 0.  Positive r indicates higher endorsement in
    the first-listed condition (ACTIVE for INTENT, PRE for TEMP); negative r
    indicates higher endorsement in the second condition (PASSIVE and POST
    respectively).  TRIGGERS shows Kendall's W (range 0 to 1), which is
    always positive.

    Points are coloured by construct using ``CONSTRUCT_COLORS``.  Filled
    markers indicate FDR-corrected p < 0.05; open markers indicate
    non-significance.  Guide lines run from the reference line (0) to each
    point for readability.  Horizontal separator lines divide construct groups.

    Parameters
    ----------
    intent_results:
        Full permutation result DataFrame for INTENT context variable.
    temp_results:
        Full permutation result DataFrame for TEMP context variable.
    trigger_results:
        Full permutation result DataFrame for TRIGGERS context variable.
    pb_order:
        PB trigger names in display order (top to bottom).
    """
    fig, axes = plt.subplots(1, 3, figsize=(18, 10), sharey=True)

    panels = [
        (intent_results,  axes[0],
         "INTENT",  (-1, 1), 0),
        (temp_results,    axes[1],
         "TEMP",        (-1, 1), 0),
        (trigger_results, axes[2],
         "TRIGGERS",                                     (0,  1), None),
    ]

    y_pos = {pb: i for i, pb in enumerate(reversed(pb_order))}

    for results_df, ax, title, xlim, ref_line in panels:
        indexed = results_df.set_index("PB")

        for pb in pb_order:
            if pb not in indexed.index:
                continue

            y         = y_pos[pb]
            eff       = indexed.loc[pb, "effect_size"]
            p_corr    = indexed.loc[pb, "p_value_corrected"] \
                        if "p_value_corrected" in indexed.columns else np.nan
            construct = get_construct(pb)
            color     = CONSTRUCT_COLORS.get(construct, "#333333")

            if pd.isna(eff):
                ax.plot(0, y, marker="x", color="lightgray", markersize=8)
                continue

            significant = (not pd.isna(p_corr)) and (float(p_corr) < 0.05)
            face_color  = color if significant else "white"

            ax.plot(
                float(eff), y,
                marker="o", markersize=10,
                color=color,
                markerfacecolor=face_color,
                markeredgecolor=color,
                markeredgewidth=1.8,
                linestyle="None",
                zorder=3,
            )
            line_start = ref_line if ref_line is not None else xlim[0]
            ax.hlines(y, line_start, float(eff),
                      colors=color, linewidth=0.5, alpha=0.4, zorder=1)

        if ref_line is not None:
            ax.axvline(ref_line, color="black", linewidth=1.0,
                       linestyle="--", alpha=0.6)

        ax.set_xlim(xlim)
        ax.set_title(title, fontsize=16, pad=8)
        # ax.set_xlabel("Effect size", fontsize=10)
        ax.set_yticks(list(y_pos.values()))
        ax.set_yticklabels(list(reversed(pb_order)), fontsize=16)
        ax.grid(axis="x", alpha=0.3)

        sb_n    = sum(1 for p in pb_order if p.startswith("SB"))
        ci_n    = sum(1 for p in pb_order if p.startswith("CI"))
        ld_n    = sum(1 for p in pb_order if p.startswith("LD"))
        n_total = len(pb_order)
        for line_idx in (sb_n, sb_n + ci_n, sb_n + ci_n + ld_n):
            y_line = n_total - line_idx - 0.5
            if 0 <= y_line < n_total:
                ax.axhline(y_line, color="black", linewidth=1.5, zorder=2)

    legend_handles = [
        plt.Line2D([0], [0], marker="o", color="w",
                   markerfacecolor="white", markeredgecolor="gray",
                   markeredgewidth=1.8, markersize=9, label="p >= 0.05 (n.s.)"),
        plt.Line2D([0], [0], marker="o", color="w",
                   markerfacecolor="gray", markeredgecolor="gray",
                   markeredgewidth=1.8, markersize=9, label="p < 0.05 (FDR corrected)"),
    ]
    fig.legend(handles=legend_handles, loc="lower center", ncol=2,
               fontsize=9, bbox_to_anchor=(0.5, -0.04))
    plt.tight_layout()
    save_and_show(fig, EVENTS_FIGURES_DIR, "fig04_effect_size_forest.png")


