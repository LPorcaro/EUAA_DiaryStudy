def compute_coccurrence(indf: pd.DataFrame) -> None:
    """
    Compute pairwise Jaccard similarity between binary trigger columns and
    render a co-occurrence network (threshold >= 0.2) and a full heatmap.

    Parameters
    ----------
    indf:
        Binary trigger matrix (columns = trigger names).
    """
    cols    = indf.columns
    n       = len(cols)
    jaccard = np.zeros((n, n))

    for i, r in enumerate(cols):
        for j, c in enumerate(cols):
            inter = (indf[r] & indf[c]).sum()
            union = (indf[r] | indf[c]).sum()
            jaccard[i, j] = inter / union if union > 0 else 0

    jaccard_df = pd.DataFrame(jaccard, index=cols, columns=cols)
    print("Co-occurrence matrix (Jaccard):\n", jaccard_df)

    # Network
    G = nx.Graph()
    node_color_map = {"SB": "#4C72B0", "CI": "#DD8452", "LD": "#55A868"}
    for col in cols:
        G.add_node(col, color=node_color_map.get(col[:2], "#808080"))

    for i in cols:
        for j in cols:
            if i != j and jaccard_df.loc[i, j] >= 0.2:
                G.add_edge(i, j, weight=jaccard_df.loc[i, j])

    pos        = nx.circular_layout(G)
    colors     = [G.nodes[nd]["color"] for nd in G.nodes()]
    weights    = [G[u][v]["weight"] * 5 for u, v in G.edges()]
    edge_labels = {(u, v): format_half_up(G[u][v]["weight"], 2) for u, v in G.edges()}

    fig_net = plt.figure(figsize=(10, 10))
    nx.draw_networkx_nodes(G, pos, node_color=colors, node_size=1200)
    # networkx defaults to font_family="sans-serif". Use the figstyle family.
    label_family = plt.rcParams["font.family"]
    nx.draw_networkx_labels(G, pos, font_size=10, font_color="white", font_weight="bold",
                            font_family=label_family)
    nx.draw_networkx_edges(G, pos, width=weights, edge_color="#aaaaaa", alpha=0.7)
    # label_pos 0.45 instead of the midpoint: the CI4-SB1 and CI1-LD2 edges
    # cross at the centre of the circle, where their midpoint labels overlapped.
    nx.draw_networkx_edge_labels(
        G, pos,
        edge_labels=edge_labels,
        label_pos=0.45,
        font_size=8,
        font_family=label_family,
        font_color="#333333",
        bbox=dict(boxstyle="round,pad=0.2", fc="white", ec="none", alpha=0.7),
    )
    legend_handles = [
        mpatches.Patch(color="#4C72B0", label="SB - Societal Bias"),
        mpatches.Patch(color="#DD8452", label="CI - Commercial Imperatives"),
        mpatches.Patch(color="#55A868", label="LD - Limited Discovery"),
    ]
    plt.legend(handles=legend_handles, loc="upper left", bbox_to_anchor=(0.6, 1.1), borderaxespad=0, fontsize=16)
    plt.axis("off")
    save_and_show(fig_net, EVENTS_FIGURES_DIR, "fig03a_cooccurrence_network.png")

    # Heatmap
    fig_hm = plt.figure(figsize=(12, 10))
    sns.heatmap(jaccard_df, annot=format_frame_half_up(jaccard_df, 2), fmt="",
                cmap="Blues")
    save_and_show(fig_hm, EVENTS_FIGURES_DIR, "fig03b_cooccurrence_heatmap.png")


