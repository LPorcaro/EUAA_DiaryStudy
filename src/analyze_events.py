def conditional_prob_ci(
    df: pd.DataFrame,
    category_col: str,
    pb_cols: list[str],
    alpha: float = 0.05,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """
    Compute P(PB | category) with binomial 95% confidence intervals
    (Clopper-Pearson beta method).

    Column order in the returned DataFrames follows ``CONTEXT_LEVEL_ORDER``
    for two-level context variables (INTENT: ACTIVE before PASSIVE; TEMP: PRE
    before POST).  For other variables (e.g. TRIGGERS) columns are sorted
    alphabetically, which yields TR1, TR2, TR3.

    Parameters
    ----------
    df:
        Event-level DataFrame containing ``category_col`` and all ``pb_cols``.
    category_col:
        Grouping variable (e.g. ``"INTENT"``).
    pb_cols:
        Binary PB trigger columns.
    alpha:
        Significance level for confidence intervals (default 0.05 -> 95%).

    Returns
    -------
    prob_df:
        Pivot table of probabilities (index = PB trigger, columns = categories).
    ci_tuples:
        Same shape as ``prob_df``; each cell holds ``(lower, upper)`` tuple.
    """
    records = []
    for cat, group in df.groupby(category_col):
        n = len(group)
        for pb in pb_cols:
            k = int(group[pb].sum())
            p_hat = k / n
            lo, hi = proportion_confint(count=k, nobs=n, alpha=alpha, method="beta")
            records.append({"category": cat, "PB_trigger": pb,
                             "probability": p_hat, "CI_lower": lo, "CI_upper": hi})

    result_df = pd.DataFrame(records)
    prob_df   = result_df.pivot(index="PB_trigger", columns="category", values="probability")
    ci_df     = result_df.pivot(index="PB_trigger", columns="category",
                                values=["CI_lower", "CI_upper"])

    # Enforce canonical column ordering
    if category_col in CONTEXT_LEVEL_ORDER:
        col_order = CONTEXT_LEVEL_ORDER[category_col]
        prob_df   = prob_df.reindex(columns=col_order)
        ci_df     = ci_df.reindex(columns=col_order, level=1)
    else:
        col_order = sorted(prob_df.columns)
        prob_df   = prob_df.reindex(columns=col_order)
        ci_df     = ci_df.reindex(columns=col_order, level=1)

    ci_tuples = pd.DataFrame(index=prob_df.index, columns=prob_df.columns)
    for r in prob_df.index:
        for c in prob_df.columns:
            ci_tuples.loc[r, c] = (ci_df["CI_lower"].loc[r, c],
                                   ci_df["CI_upper"].loc[r, c])
    return prob_df, ci_tuples


