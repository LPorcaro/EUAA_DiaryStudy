def plot_trigger_temp_intent(df: pd.DataFrame) -> pd.DataFrame:
    """
    Horizontal stacked bar chart of TEMP x INTENT counts per platform TRIGGER,
    with a summary table appended below.
    Stacking order follows the canonical level ordering: PRE before POST,
    ACTIVE before PASSIVE within each temporal group.
    Parameters
    ----------
    df:
        Must contain columns ``TRIGGERS``, ``TEMP`` (PRE/POST),
        and ``INTENT`` (ACTIVE/PASSIVE).
    Returns
    -------
    Integer count table (DataFrame).
    """
    FONT_SIZE = 16
    TITLE_SIZE = 14

    counts = (
        df.groupby(["TRIGGERS", "TEMP", "INTENT"])
          .size()
          .reset_index(name="count")
    )
    triggers = counts["TRIGGERS"].unique()
    # Order: PRE ACTIVE, PRE PASSIVE, POST ACTIVE, POST PASSIVE
    color_map = {
        ("PRE",  "ACTIVE"):  "#87CEFA",
        ("PRE",  "PASSIVE"): "#1E90FF",
        ("POST", "ACTIVE"):  "#FFA07A",
        ("POST", "PASSIVE"): "#FF8C00",
    }
    table = (
        counts.pivot_table(
            index="TRIGGERS", columns=["TEMP", "INTENT"],
            values="count", fill_value=0,
        )
    )
    table.columns = [f"{t}_{i}" for t, i in table.columns]
    table = table.reset_index()
    table_int = table.copy()
    for col in table_int.columns[1:]:
        table_int[col] = table_int[col].astype(int)

    fig, ax = plt.subplots(figsize=(14, 6))
    bottom = np.zeros(len(triggers))
    for temp_intent, color in color_map.items():
        mask = (
            (counts["TEMP"]   == temp_intent[0]) &
            (counts["INTENT"] == temp_intent[1])
        )
        values = (
            counts[mask]
            .set_index("TRIGGERS")
            .reindex(triggers)["count"]
            .fillna(0)
        )
        ax.barh(triggers, values, left=bottom, color=color,
                label=f"{temp_intent[0]} {temp_intent[1]}")
        bottom += values

    # ax.set(xlabel="Count")

    ax.xaxis.label.set_size(FONT_SIZE)
    ax.tick_params(axis="both", labelsize=FONT_SIZE)
    ax.legend(title="TEMP x INTENT", loc="lower right",
              fontsize=FONT_SIZE, title_fontsize=TITLE_SIZE)
    ax.invert_yaxis()

    tbl = plt.table(
        cellText=table_int.values,
        colLabels=table_int.columns,
        loc="bottom", cellLoc="center",
        bbox=[0, -0.55, 1, 0.38],
    )
    tbl.auto_set_font_size(False)
    tbl.set_fontsize(FONT_SIZE)
    for (row, col), cell in tbl.get_celld().items():
        cell.set_height(0.07)

    plt.subplots_adjust(left=0.18, bottom=0.38)
    plt.tight_layout(rect=[0, 0.38, 1, 1])
    save_and_show(fig, EVENTS_FIGURES_DIR, "fig01_trigger_temp_intent.png")
    return table_int

