def map_pb_list(statements: list[str]) -> list[tuple[str, int]]:
    """
    Map a list of Italian PB statements to (construct, item_id) tuples.

    Unrecognised statements fall back to ``("O", 2)``.

    Parameters
    ----------
    statements:
        Raw strings as selected by a participant.

    Returns
    -------
    list of (construct, item_id) tuples.
    """
    return [PB_DICT.get(s.strip(), ("O", 2)) for s in statements]


# No PB statement may contain another one, otherwise substring matching in
# extract_pb_statements would be ambiguous.
assert not any(a != b and a in b for a in PB_DICT for b in PB_DICT), \
    "A PB_DICT statement is a substring of another statement"


def extract_pb_statements(cell: object) -> tuple[list[str], str]:
    """
    Extract the predefined PB statements from one raw ``PB1``/``PB2`` cell.

    The form stores every selected option in one comma-joined string. The
    free-text "Other" answer (O2) can itself contain commas, so the cell is
    not split on commas. Each known statement in ``PB_DICT`` is matched
    exactly and removed. Whatever text remains is the O2 free-text answer,
    which is returned separately and excluded from the analysis.

    Parameters
    ----------
    cell:
        Raw cell value (string or NaN).

    Returns
    -------
    statements:
        Known statements found in the cell.
    free_text:
        Remaining free text (empty string if none).
    """
    if not isinstance(cell, str):
        return [], ""
    found: list[str] = []
    rest = cell
    for statement in sorted(PB_DICT, key=len, reverse=True):
        if statement in rest:
            found.append(statement)
            rest = rest.replace(statement, "", 1)
    free_text = rest.strip(" ,\t\n")
    return found, free_text


def parse_pb_selections(df: pd.DataFrame) -> tuple[pd.Series, pd.Series]:
    """
    Map the ``PB1`` and ``PB2`` columns to (construct, item_id) tuples.

    O2 free-text answers are separated before any parsing (see
    :func:`extract_pb_statements`) and are not mapped to any item.

    Returns
    -------
    pb_mapped:
        Per event, the list of (construct, item_id) tuples.
    o2_text:
        Per event, the O2 free-text answers joined with `` | `` (empty if none).
    """
    mapped, o2 = [], []
    for _, row in df.iterrows():
        statements: list[str] = []
        free: list[str] = []
        for col in ("PB1", "PB2"):
            found, text = extract_pb_statements(row[col])
            statements += found
            if text:
                free.append(text)
        mapped.append(map_pb_list(statements))
        o2.append(" | ".join(free))
    return pd.Series(mapped, index=df.index), pd.Series(o2, index=df.index)


def remap_trigger(cat: str, num: int) -> str:
    """
    Apply the revised measurement model: SB4 is reassigned to CI5.

    Parameters
    ----------
    cat : construct label (e.g. ``"SB"``)
    num : item number

    Returns
    -------
    Column name string (e.g. ``"CI5"`` or ``"LD2"``).
    """
    if cat == "SB" and num == 4:
        return "CI5"
    return f"{cat}{num}"


#: Revised-model PB columns plus O1, in reporting order.
REVISED_PB_COLS_WITH_O: list[str] = [
    "SB1", "SB2", "SB3",
    "CI1", "CI2", "CI3", "CI4", "CI5",
    "LD1", "LD2", "LD3", "LD4",
    "O1",
]


def build_revised_binary_matrix(
    pb_mapped: pd.Series,
    pb_cols: list[str] = REVISED_PB_COLS_WITH_O,
) -> pd.DataFrame:
    """
    Binary event-by-item matrix under the revised model (SB4 -> CI5).

    Parameters
    ----------
    pb_mapped:
        Per event, the list of (construct, item_id) tuples returned by
        :func:`parse_pb_selections`.
    pb_cols:
        Columns to keep. Items outside this list (e.g. O2) are ignored.
    """
    out = pd.DataFrame(0, index=pb_mapped.index, columns=pb_cols)
    for i, mapped in pb_mapped.items():
        for col in (remap_trigger(cat, num) for cat, num in mapped):
            if col in pb_cols:
                out.loc[i, col] = 1
    return out


def get_construct(trigger: str) -> str:
    """Return the construct prefix for a trigger column name."""
    for prefix in ("SB", "CI", "LD"):
        if trigger.startswith(prefix):
            return prefix
    return "O"


