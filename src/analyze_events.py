def compute_descriptive_summary(
    df: pd.DataFrame,
    binary_mod_O_df: pd.DataFrame,
    pb_cols: list[str],
    likerts: list[str],
    pid_col: str = "PID",
) -> pd.DataFrame:
    """
    Produce a paper-ready descriptive summary table.

    Rows cover per-participant event counts, Likert means, and PB proportions,
    plus an OVERALL aggregate row.  Construct-level prevalence columns are
    appended as the mean of member item proportions.

    Parameters
    ----------
    df:
        Raw event-level DataFrame (must contain ``pid_col``, Likert columns,
        ``INTENT``, ``TEMP``, ``TRIGGERS``).
    binary_mod_O_df:
        Binary trigger matrix aligned with ``df`` index.
    pb_cols:
        Ordered list of PB trigger column names.
    likerts:
        Likert outcome column names.
    pid_col:
        Participant ID column.

    Returns
    -------
    summary_df:
        Wide-format summary DataFrame (also printed to stdout).
    """
    combined = pd.concat([df, binary_mod_O_df], axis=1)

    participant_rows = []
    for pid, grp in combined.groupby(pid_col):
        row: dict = {
            "ID":        pid,
            "N_events":  len(grp),
            "N_PRE":     int((grp["TEMP"]   == "PRE").sum()),
            "N_POST":    int((grp["TEMP"]   == "POST").sum()),
            "N_ACTIVE":  int((grp["INTENT"] == "ACTIVE").sum()),
            "N_PASSIVE": int((grp["INTENT"] == "PASSIVE").sum()),
        }
        for q in likerts:
            row[f"{q}_mean"] = round(grp[q].mean(), 2)
        for pb in pb_cols:
            row[f"{pb}_prop"] = round(grp[pb].mean(), 3)
        participant_rows.append(row)

    participant_df = pd.DataFrame(participant_rows).set_index("ID")

    overall: dict = {
        "ID":        "OVERALL",
        "N_events":  len(combined),
        "N_PRE":     int((combined["TEMP"]   == "PRE").sum()),
        "N_POST":    int((combined["TEMP"]   == "POST").sum()),
        "N_ACTIVE":  int((combined["INTENT"] == "ACTIVE").sum()),
        "N_PASSIVE": int((combined["INTENT"] == "PASSIVE").sum()),
    }
    for q in likerts:
        overall[f"{q}_mean"] = round(combined[q].mean(), 2)
    for pb in pb_cols:
        overall[f"{pb}_prop"] = round(combined[pb].mean(), 3)

    summary_df = pd.concat(
        [participant_df, pd.DataFrame([overall]).set_index("ID")]
    )

    for c in ("SB", "CI", "LD", "O"):
        cols = [p for p in pb_cols if get_construct(p) == c]
        if cols:
            summary_df[f"{c}_prevalence"] = (
                summary_df[[f"{p}_prop" for p in cols]].mean(axis=1).round(3)
            )

    print("\n=== Descriptive Summary Table ===")
    print(summary_df.to_string())
    return summary_df


