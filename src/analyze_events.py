def compute_reliability_wide_table(indf: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    """
    Compute Cronbach alpha, item-total correlations, and alpha-if-deleted for
    constructs SB, CI, and LD.

    Parameters
    ----------
    indf:
        Binary item matrix; columns named ``"SB1"``, ``"CI3"``, etc.

    Returns
    -------
    table_alpha:
        One row per construct with alpha and 95% confidence interval (2 d.p.).
        The interval column is labelled ``"Alpha_95CI"`` to avoid confusion
        with the CI (Commercial Interests) construct abbreviation.
    table_items:
        Two rows (item-total correlations / alpha-if-deleted) x all item
        columns (2 d.p.).
    """
    alpha_rows, itc_wide, aifd_wide = [], {}, {}

    for construct in ("SB", "CI", "LD"):
        items    = [c for c in indf.columns if c.startswith(construct)]
        df_items = indf[items]

        alpha_val, ci95 = pg.cronbach_alpha(df_items)
        alpha_rows.append({
            "Construct":  construct,
            "Alpha":      round(alpha_val, 2),
            "Alpha_95CI": f"[{round(ci95[0], 2)}, {round(ci95[1], 2)}]",
        })

        total = df_items.sum(axis=1)
        for col in items:
            itc_wide[col]  = round(df_items[col].corr(total - df_items[col]), 2)
            aifd_wide[col] = round(pg.cronbach_alpha(df_items.drop(columns=[col]))[0], 2)

    table_alpha = pd.DataFrame(alpha_rows)
    table_items = pd.DataFrame(
        [itc_wide, aifd_wide],
        index=["Item-total correlations", "Alpha if Deleted"],
    )
    return table_alpha, table_items


