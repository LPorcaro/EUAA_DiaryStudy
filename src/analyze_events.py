def feldt_interval(alpha: float, n: int, k: int, level: float = 0.95) -> tuple[float, float]:
    """
    Feldt's confidence interval for Cronbach's alpha, at full precision.

    Same formula as ``pingouin.cronbach_alpha`` (Feldt, Woodruff and Salih,
    1987, as cited in the pingouin documentation). pingouin rounds its
    bounds to 3 decimals before returning them, so the pipeline computes
    them here to round reported values only once.

    Parameters
    ----------
    alpha: Cronbach's alpha.
    n: number of observations (events).
    k: number of items.
    level: confidence level.
    """
    tail = 1 - level
    df1, df2 = n - 1, (n - 1) * (k - 1)
    lower = 1 - (1 - alpha) * f_dist.isf(tail / 2, df1, df2)
    upper = 1 - (1 - alpha) * f_dist.isf(1 - tail / 2, df1, df2)
    return float(lower), float(upper)


def compute_reliability_wide_table(indf: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    """
    Compute Cronbach alpha, item-total correlations, and alpha-if-deleted for
    constructs SB, CI, and LD.

    Parameters
    ----------
    indf:
        Binary item matrix; columns named ``"SB1"``, ``"CI3"``, etc.

    Returns
    -------
    table_alpha:
        One row per construct with alpha and 95% confidence interval (2 d.p.).
        The interval column is labelled ``"Alpha_95CI"`` to avoid confusion
        with the CI (Commercial Interests) construct abbreviation.
    table_items:
        Two rows (item-total correlations / alpha-if-deleted) x all item
        columns (2 d.p.).
    """
    alpha_rows, itc_wide, aifd_wide = [], {}, {}

    for construct in ("SB", "CI", "LD"):
        items    = [c for c in indf.columns if c.startswith(construct)]
        df_items = indf[items]

        alpha_val, _ = pg.cronbach_alpha(df_items)
        ci95 = feldt_interval(alpha_val, *df_items.shape)
        alpha_rows.append({
            "Construct":  construct,
            "Alpha":      round_half_up(alpha_val, 2),
            "Alpha_95CI": f"[{format_half_up(ci95[0], 2)}, {format_half_up(ci95[1], 2)}]",
        })

        total = df_items.sum(axis=1)
        for col in items:
            itc_wide[col]  = round_half_up(df_items[col].corr(total - df_items[col]), 2)
            aifd_wide[col] = round_half_up(pg.cronbach_alpha(df_items.drop(columns=[col]))[0], 2)

    table_alpha = pd.DataFrame(alpha_rows)
    table_items = pd.DataFrame(
        [itc_wide, aifd_wide],
        index=["Item-total correlations", "Alpha if Deleted"],
    )
    return table_alpha, table_items


