def plot_trigger_temp_intent(df: pd.DataFrame) -> pd.DataFrame:
    """
    Horizontal stacked bar chart of TEMP x INTENT counts per platform TRIGGER,
    with a summary table appended below.
    Stacking order follows the canonical level ordering: PRE before POST,
    ACTIVE before PASSIVE within each temporal group.
    Parameters
    ----------
    df:
        Must contain columns ``TRIGGERS``, ``TEMP`` (PRE/POST),
        and ``INTENT`` (ACTIVE/PASSIVE).
    Returns
    -------
    Integer count table (DataFrame).
    """
    FONT_SIZE = 16
    LEGEND_SIZE = 12        # legend entries
    LEGEND_TITLE_SIZE = 11  # legend title
    # Layout in figure fractions and inches, so that it does not depend on
    # the glyph metrics of the chosen font.
    AXES_BAND = [0, 0.45, 1, 1]  # tight_layout band for the axes and legend
    TABLE_GAP_IN = 0.08          # gap between tick labels and table
    TABLE_ROW_IN = 0.30          # height of each table row

    counts = (
        df.groupby(["TRIGGERS", "TEMP", "INTENT"])
          .size()
          .reset_index(name="count")
    )
    triggers = counts["TRIGGERS"].unique()
    # Order: PRE ACTIVE, PRE PASSIVE, POST ACTIVE, POST PASSIVE
    color_map = {
        ("PRE",  "ACTIVE"):  "#87CEFA",
        ("PRE",  "PASSIVE"): "#1E90FF",
        ("POST", "ACTIVE"):  "#FFA07A",
        ("POST", "PASSIVE"): "#FF8C00",
    }
    table = (
        counts.pivot_table(
            index="TRIGGERS", columns=["TEMP", "INTENT"],
            values="count", fill_value=0,
        )
    )
    table.columns = [f"{t}_{i}" for t, i in table.columns]
    table = table.reset_index()
    table_int = table.copy()
    for col in table_int.columns[1:]:
        table_int[col] = table_int[col].astype(int)

    fig, ax = plt.subplots(figsize=(14, 6))
    bottom = np.zeros(len(triggers))
    for temp_intent, color in color_map.items():
        mask = (
            (counts["TEMP"]   == temp_intent[0]) &
            (counts["INTENT"] == temp_intent[1])
        )
        values = (
            counts[mask]
            .set_index("TRIGGERS")
            .reindex(triggers)["count"]
            .fillna(0)
        )
        ax.barh(triggers, values, left=bottom, color=color,
                label=f"{temp_intent[0]} {temp_intent[1]}")
        bottom += values

    # ax.set(xlabel="Count")

    ax.xaxis.label.set_size(FONT_SIZE)
    ax.tick_params(axis="both", labelsize=FONT_SIZE)
    # Legend in one row above the axes, so it covers no bar.
    ax.legend(title="TEMP x INTENT", loc="lower center", bbox_to_anchor=(0.5, 1.02),
              ncol=4, fontsize=LEGEND_SIZE, title_fontsize=LEGEND_TITLE_SIZE)
    ax.invert_yaxis()

    # The axes and legend fill a fixed band. The table is created after the
    # tight layout pass, so it does not change the band, and is placed below
    # the measured tick labels. It stays in the layout so that the saved
    # tight bounding box includes it.
    plt.tight_layout(rect=AXES_BAND)
    fig.canvas.draw()
    renderer = fig.canvas.get_renderer()
    ax_box = ax.get_window_extent(renderer)
    tick_bottom = min(
        lab.get_window_extent(renderer).y0
        for lab in ax.get_xticklabels()
        if lab.get_text() and ax_box.x0 <= lab.get_window_extent(renderer).x0 <= ax_box.x1
    )
    ax_h_in = ax_box.height / fig.dpi
    n_rows = len(table_int) + 1  # header plus one row per trigger
    table_h = n_rows * TABLE_ROW_IN / ax_h_in
    table_top = -((ax_box.y0 - tick_bottom) / fig.dpi + TABLE_GAP_IN) / ax_h_in
    tbl = plt.table(
        cellText=table_int.values,
        colLabels=table_int.columns,
        loc="bottom", cellLoc="center",
        bbox=[0, table_top - table_h, 1, table_h],
    )
    tbl.auto_set_font_size(False)
    tbl.set_fontsize(FONT_SIZE)

    # Fail loudly if a different font no longer fits this layout.
    fig.canvas.draw()
    cells = tbl.get_celld().values()
    if min(c.get_window_extent(renderer).y0 for c in cells) < 0:
        raise RuntimeError("fig01 table extends below the figure canvas. "
                           "Lower AXES_BAND[1] or TABLE_ROW_IN.")
    if any(c.get_text().get_window_extent(renderer).height
           > c.get_window_extent(renderer).height for c in cells):
        raise RuntimeError("fig01 table text is taller than its rows. "
                           "Increase TABLE_ROW_IN.")
    save_and_show(fig, EVENTS_FIGURES_DIR, "fig01_trigger_temp_intent.png")
    return table_int

