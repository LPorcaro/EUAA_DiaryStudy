def aggregate_to_construct_level(
    prob_df: pd.DataFrame,
    pb_cols: list[str],
) -> pd.DataFrame:
    """
    Category-level P(PB | context) as the unweighted mean of the item-level
    conditional probabilities in each category.

    This is the primary definition. It matches the values reported in the
    paper (Section 5.2.4, Figure 3). No interval is computed at category
    level. Clopper-Pearson intervals are reported at item level only.

    Parameters
    ----------
    prob_df:
        Item-level conditional probabilities
        (index = PB trigger, columns = context levels).
    pb_cols:
        Ordered PB column list used to identify construct membership.

    Returns
    -------
    Construct-level probabilities (index = construct, columns = context).
    """
    prob_rows: dict = {}
    for c in ("SB", "CI", "LD", "O"):
        items = [p for p in pb_cols if get_construct(p) == c]
        if not items or not all(i in prob_df.index for i in items):
            continue
        prob_rows[c] = prob_df.loc[items].mean()

    construct_prob_df = pd.DataFrame(prob_rows).T
    construct_prob_df.index.name = "construct"
    return construct_prob_df


def sensitivity_any_item_construct_probs(
    df: pd.DataFrame,
    category_col: str,
    pb_cols: list[str],
) -> pd.DataFrame:
    """
    Sensitivity check, NOT REPORTED IN THE PAPER.

    Puts the primary category-level value (``mean_of_items``, the same
    number as in ``construct_probs_*.csv``) next to an alternative,
    ``any_item``, the share of events in which at least one item of the
    category was ticked (``any_item_k`` of ``n_events``). No interval is
    given for either.

    Returns
    -------
    Long-format DataFrame with one row per (level, construct).
    """
    if category_col in CONTEXT_LEVEL_ORDER:
        levels = CONTEXT_LEVEL_ORDER[category_col]
    else:
        levels = sorted(df[category_col].unique())

    rows: list[dict] = []
    for level in levels:
        group = df[df[category_col] == level]
        n = len(group)
        for c in ("SB", "CI", "LD", "O"):
            items = [p for p in pb_cols if get_construct(p) == c]
            k = int((group[items].sum(axis=1) > 0).sum())
            rows.append({
                "context":       category_col,
                "level":         level,
                "construct":     c,
                "n_items":       len(items),
                "n_events":      n,
                "mean_of_items": round_half_up(group[items].mean().mean(), 3),
                "any_item_k":    k,
                "any_item":      round_half_up(k / n, 3),
            })
    return pd.DataFrame(rows)


