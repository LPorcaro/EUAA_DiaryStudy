def map_pb_list(statements: list[str]) -> list[tuple[str, int]]:
    """
    Map a list of Italian PB statements to (construct, item_id) tuples.

    Unrecognised statements fall back to ``("O", 2)``.

    Parameters
    ----------
    statements:
        Raw strings as selected by a participant.

    Returns
    -------
    list of (construct, item_id) tuples.
    """
    return [PB_DICT.get(s.strip(), ("O", 2)) for s in statements]


def remap_trigger(cat: str, num: int) -> str:
    """
    Apply the revised measurement model: SB4 is reassigned to CI5.

    Parameters
    ----------
    cat : construct label (e.g. ``"SB"``)
    num : item number

    Returns
    -------
    Column name string (e.g. ``"CI5"`` or ``"LD2"``).
    """
    if cat == "SB" and num == 4:
        return "CI5"
    return f"{cat}{num}"


def get_construct(trigger: str) -> str:
    """Return the construct prefix for a trigger column name."""
    for prefix in ("SB", "CI", "LD"):
        if trigger.startswith(prefix):
            return prefix
    return "O"


