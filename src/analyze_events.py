def export_conditional_results_csv(
    prob_df: pd.DataFrame,
    ci_df: pd.DataFrame,
    effect_df: pd.DataFrame,
    effect_results: pd.DataFrame,
    *,
    context_name: str,
    pb_order: list[str],
    output_path: str | Path,
) -> pd.DataFrame:
    """
    Write conditional probabilities, confidence intervals, and effect sizes
    to CSV.

    Columns per context level are ``{level}_prob``, ``{level}_ci_low`` and
    ``{level}_ci_high``. The final column is ``exploratory_effect_size``.
    It is not reported in the paper. A companion note,
    ``conditional_probs_NOTE.txt``, is written next to the CSV files.

    Parameters
    ----------
    prob_df:
        Conditional probabilities (index = PB, columns = context levels).
    ci_df:
        Confidence interval tuples, same shape as ``prob_df``.
    effect_df:
        Single-column effect sizes.
    effect_results:
        Full effect-size results (output of
        :func:`compute_conditional_prob_effect_sizes`).
    context_name:
        Label used in print output only.
    pb_order:
        Row ordering for the output CSV.
    output_path:
        Destination file path.

    Returns
    -------
    The exported DataFrame (also written to ``output_path``).
    """
    eff_idx = effect_results.set_index("PB")
    rows: list[dict] = []

    for r in pb_order:
        row: dict = {
            "PB":        r,
            "construct": r[:2] if r != "O1" else "O",
        }

        for c in prob_df.columns:
            prob   = float(prob_df.loc[r, c])
            lo, hi = prob, prob
            if ci_df is not None:
                cell = ci_df.loc[r, c]
                if isinstance(cell, (tuple, list)) and len(cell) == 2:
                    lo, hi = float(cell[0]), float(cell[1])
            row[f"{c}_prob"]    = round_half_up(prob, 3)
            row[f"{c}_ci_low"]  = round_half_up(lo,   3)
            row[f"{c}_ci_high"] = round_half_up(hi,   3)

        if r in eff_idx.index:
            ev = eff_idx.loc[r, "effect_size"] \
                 if "effect_size" in eff_idx.columns else np.nan
            row[f"{EXPLORATORY_PREFIX}effect_size"] = (
                round_half_up(ev, 3) if not pd.isna(ev) else np.nan
            )
        else:
            row[f"{EXPLORATORY_PREFIX}effect_size"] = np.nan

        rows.append(row)

    out_df      = pd.DataFrame(rows).set_index("PB")
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    out_df.to_csv(output_path)
    print(f"[export] {context_name} -> {output_path}")
    return out_df


