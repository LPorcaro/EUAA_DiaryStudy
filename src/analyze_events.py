# ---------------------------------------------------------------------------
# Main pipeline
# ---------------------------------------------------------------------------

def main(input_path: str | Path = RAW_EVENTS_PATH) -> None:
    """
    Run the full AA4MD analysis pipeline.

    Parameters
    ----------
    input_path:
        Path to the raw events CSV. Defaults to ``data/events_20260324.csv``
        (see ``config.RAW_EVENTS_PATH``).
    """
    ensure_output_dirs()

    # 1. Load data
    df = pd.read_csv(input_path)

    # 2. Visualise event distribution
    summary_table = plot_trigger_temp_intent(df)
    print(summary_table)

    # 3. Parse PB selections
    df["PB1_split"] = df["PB1"].str.split(",")
    df["PB2_split"] = df["PB2"].str.split(",")
    df["PB"] = df.apply(
        lambda row: (row["PB1_split"] if isinstance(row["PB1_split"], list) else [])
                  + (row["PB2_split"] if isinstance(row["PB2_split"], list) else []),
        axis=1,
    )
    df["PB_mapped"] = df["PB"].apply(map_pb_list)

    # 4. Original measurement model
    ORIG_COLS = ["SB1","SB2","SB3","SB4",
                 "CI1","CI2","CI3","CI4",
                 "LD1","LD2","LD3","LD4"]
    binary_df = pd.DataFrame(0, index=df.index, columns=ORIG_COLS)
    for i, row in df.iterrows():
        for cat, num in row["PB_mapped"]:
            col = f"{cat}{num}"
            if col in ORIG_COLS:
                binary_df.loc[i, col] = 1

    alpha_orig, items_orig = compute_reliability_wide_table(binary_df)
    print("=== Original model -- Cronbach alpha ===")
    print(alpha_orig)
    print("\n=== Original model -- Item statistics ===")
    print(items_orig)

    # 5. Revised model (SB4 -> CI5)
    REVISED_COLS = ["SB1","SB2","SB3",
                    "CI1","CI2","CI3","CI4","CI5",
                    "LD1","LD2","LD3","LD4"]
    binary_mod_df = pd.DataFrame(0, index=df.index, columns=REVISED_COLS)
    for i, row in df.iterrows():
        for col in (remap_trigger(cat, num) for cat, num in row["PB_mapped"]):
            if col in REVISED_COLS:
                binary_mod_df.loc[i, col] = 1

    alpha_mod, items_mod = compute_reliability_wide_table(binary_mod_df)
    print("\n=== Revised model -- Cronbach alpha ===")
    print(alpha_mod)
    print("\n=== Revised model -- Item statistics ===")
    print(items_mod)

    # 6. Likert inter-correlations + distributions
    df_analysis = pd.concat([df, binary_mod_df], axis=1)
    LIKERTS = ["ALGO_CAUSE", "FUTURE_USE", "ARTIST_HARM"]

    print("\nEvent-level Spearman correlations (Likert):")
    print(df_analysis[LIKERTS].corr(method="spearman"))

    df_melt = df_analysis[LIKERTS].melt(var_name="Likert", value_name="Score")
    fig_box = plt.figure(figsize=(8, 6))
    sns.boxplot(x="Likert", y="Score", data=df_melt, hue="Likert",
                dodge=False, palette="pastel", showfliers=True)
    sns.stripplot(x="Likert", y="Score", data=df_melt,
                  color="gray", size=4, jitter=True, alpha=0.6)
    plt.ylabel("Score")
    plt.xlabel("")
    plt.legend([], [], frameon=False)
    save_and_show(fig_box, EVENTS_FIGURES_DIR, "fig00_likert_distributions.png")

    summary = pd.DataFrame({
        "N":      df_analysis[LIKERTS].count(),
        "Mean":   df_analysis[LIKERTS].mean(),
        "SD":     df_analysis[LIKERTS].std(),
        "Median": df_analysis[LIKERTS].median(),
        "Q1":     df_analysis[LIKERTS].quantile(0.25),
        "Q3":     df_analysis[LIKERTS].quantile(0.75),
        "Min":    df_analysis[LIKERTS].min(),
        "Max":    df_analysis[LIKERTS].max(),
    }).round(2)

    print("\nDescriptive Statistics — Likert Items")
    print(summary.to_string())

    # 7. Build binary matrix including O category
    sb_cols = [c for c in binary_mod_df.columns if c.startswith("SB")]
    ci_cols = [c for c in binary_mod_df.columns if c.startswith("CI")]
    ld_cols = [c for c in binary_mod_df.columns if c.startswith("LD")]
    o_cols  = ["O1"]
    pb_cols = sb_cols + ci_cols + ld_cols + o_cols

    binary_mod_O_df = pd.DataFrame(0, index=df.index, columns=pb_cols)
    for i, row in df.iterrows():
        for col in (remap_trigger(cat, num) for cat, num in row["PB_mapped"]):
            if col in pb_cols:
                binary_mod_O_df.loc[i, col] = 1

    df_analysis_O = pd.concat([df, binary_mod_O_df], axis=1)

    # 7b. Export enriched event-level DataFrame
    event_enriched = df_analysis_O.drop(
        columns=["PB1_split", "PB2_split", "PB", "PB_mapped"],
        errors="ignore",
    )
    out_events = ENRICHED_EVENTS_PATH
    out_events.parent.mkdir(parents=True, exist_ok=True)
    event_enriched.to_csv(out_events, index=False)
    print(f"[export] Enriched events -> {out_events}")
    print(f"         Shape: {event_enriched.shape}")
    print(f"         Columns: {event_enriched.columns.tolist()}")

    # 8. Co-occurrence analysis
    print("\n=== Co-occurrence analysis (revised model) ===")
    compute_coccurrence(binary_mod_df)

    # 9. Conditional probabilities
    # Column order is enforced inside conditional_prob_ci via CONTEXT_LEVEL_ORDER:
    # INTENT -> [ACTIVE, PASSIVE]; TEMP -> [PRE, POST]; TRIGGERS -> [TR1, TR2, TR3]
    intent_probs,  intent_ci   = conditional_prob_ci(df_analysis_O, "INTENT",   pb_cols)
    temp_probs,    temp_ci     = conditional_prob_ci(df_analysis_O, "TEMP",     pb_cols)
    trigger_probs, trigger_ci  = conditional_prob_ci(df_analysis_O, "TRIGGERS", pb_cols)

    # 10. Construct-level aggregation + grouped bar chart
    intent_c,  intent_ci_c   = aggregate_to_construct_level(intent_probs,  intent_ci,  pb_cols)
    temp_c,    temp_ci_c     = aggregate_to_construct_level(temp_probs,    temp_ci,    pb_cols)
    trigger_c, trigger_ci_c  = aggregate_to_construct_level(trigger_probs, trigger_ci, pb_cols)

    print("\n=== Construct-level probabilities (INTENT) ===")
    print(intent_c.round(3))
    print("\n=== Construct-level probabilities (TEMP) ===")
    print(temp_c.round(3))
    print("\n=== Construct-level probabilities (TRIGGERS) ===")
    print(trigger_c.round(3))

    plot_construct_level_probs(intent_c, temp_c, trigger_c)

    for label, cdf in (("INTENT", intent_c), ("TEMP", temp_c), ("TRIGGERS", trigger_c)):
        p = TABLES_DIR / f"construct_probs_{label}.csv"
        cdf.round(3).to_csv(p)
        print(f"[export] Construct probs {label} -> {p}")

    # 11. Permutation tests
    intent_results  = permutation_test_conditional_prob(
        df_analysis_O, pb_cols, "INTENT",   n_permutations=10_000)
    temp_results    = permutation_test_conditional_prob(
        df_analysis_O, pb_cols, "TEMP",     n_permutations=10_000)
    trigger_results = permutation_test_conditional_prob(
        df_analysis_O, pb_cols, "TRIGGERS", n_permutations=10_000)

    # 12. Assemble plotting inputs
    pb_order = pb_cols

    intent_effect,  intent_pval  = build_effect_pval_dfs(intent_results,  pb_order)
    temp_effect,    temp_pval    = build_effect_pval_dfs(temp_results,    pb_order)
    trigger_effect, trigger_pval = build_effect_pval_dfs(trigger_results, pb_order)

    intent_probs  = intent_probs.reindex(pb_order)
    temp_probs    = temp_probs.reindex(pb_order)
    trigger_probs = trigger_probs.reindex(pb_order)
    intent_ci     = intent_ci.reindex(pb_order)
    temp_ci       = temp_ci.reindex(pb_order)
    trigger_ci    = trigger_ci.reindex(pb_order)

    # 13. Effect size forest plot
    plot_effect_size_forest(intent_results, temp_results, trigger_results, pb_order)

    # 14. Item-level conditional probability heatmaps
    plot_conditional_distr_with_effects(
        intent_probs, temp_probs, trigger_probs,
        ci_intent_df=intent_ci,           ci_temp_df=temp_ci,           ci_trigger_df=trigger_ci,
        effect_intent_df=intent_effect,   effect_temp_df=temp_effect,   effect_trigger_df=trigger_effect,
        pval_intent_df=intent_pval,       pval_temp_df=temp_pval,       pval_trigger_df=trigger_pval,
        pb_order=pb_order,
    )

    # 15. Export conditional probability CSVs
    for label, probs, ci, eff, pval, perm in (
        ("INTENT",   intent_probs,  intent_ci,  intent_effect,  intent_pval,  intent_results),
        ("TEMP",     temp_probs,    temp_ci,    temp_effect,    temp_pval,    temp_results),
        ("TRIGGERS", trigger_probs, trigger_ci, trigger_effect, trigger_pval, trigger_results),
    ):
        export_conditional_results_csv(
            probs, ci, eff, pval, perm,
            context_name=label,
            pb_order=pb_order,
            output_path=TABLES_DIR / f"conditional_probs_{label}.csv",
        )

    # 16. Participant-level Likert x PB correlations
    corr_df, pval_raw_df, pval_corr_df = compute_likert_pb_correlations(
        df_analysis_O, LIKERTS, pb_cols
    )

    print("\n=== Participant-level Spearman rho (Likert x PB) ===")
    print(corr_df)
    print("\n=== FDR-corrected p-values (within-Likert) ===")
    print(pval_corr_df)

    plot_likert_pb_heatmap(corr_df, pval_corr_df, pb_cols)

    export_likert_pb_csv(
        corr_df, pval_raw_df, pval_corr_df,
        output_path=TABLES_DIR / "likert_pb_correlations.csv",
    )


