    ci_cols = [c for c in binary_mod_df.columns if c.startswith("CI")]
    ld_cols = [c for c in binary_mod_df.columns if c.startswith("LD")]
    o_cols  = ["O1"]
    pb_cols = sb_cols + ci_cols + ld_cols + o_cols

