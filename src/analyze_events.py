"""
analyze_events.py
=================
This script analyses events in which participants reported 
perceived Problematic Algorithmic Behaviours (PBs)
during music-platform use.

Pipeline
--------
1.  Load raw EMA event data.
2.  Parse and map free-text PB selections to a structured taxonomy.
3.  Assess scale reliability (Cronbach α, item-total correlations).
4.  Revise the measurement model (SB4 → CI5).
5.  Descriptive summary table (events, PB prevalence, Likert means).
6.  Compute Spearman correlations between Likert outcome items.
7.  Co-occurrence analysis (Jaccard network + heatmap).
8.  Construct-level aggregation of conditional probabilities.
9.  Estimate conditional probabilities P(PB | context) with 95 % CIs.
10. Test differences across context levels via permutation tests
    (sign-flip Wilcoxon for 2-level; Friedman for ≥3-level).
11. Apply Benjamini–Hochberg FDR correction.
12. Effect size forest plot across contexts.
13. Visualise results as annotated heatmaps.
14. Export results to CSV.
15. Participant-level Likert × PB correlations.

Constructs
----------
SB  Societal Bias
CI  Commercial Interests
LD  Limited Discovery
O   Other / unclassified

Effect size conventions
-----------------------
INTENT   rank-biserial r  — positive = more frequent in ACTIVE than PASSIVE
TEMP     rank-biserial r  — positive = more frequent in PRE than POST
TRIGGERS Kendall's W      — always positive (0–1)

Input
-----
data/events_20260324.csv  (see config.RAW_EVENTS_PATH)

Output
------
outputs/figures/events/*.png   — all figures generated by this script
outputs/tables/events_enriched.csv
outputs/tables/construct_probs_{INTENT,TEMP,TRIGGERS}.csv
outputs/tables/conditional_probs_{INTENT,TEMP,TRIGGERS}.csv
outputs/tables/likert_pb_correlations.csv
"""

