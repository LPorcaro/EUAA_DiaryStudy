def plot_construct_level_probs(
    intent_c: pd.DataFrame,
    temp_c: pd.DataFrame,
    trigger_c: pd.DataFrame,
) -> None:
    """
    Grouped bar chart of construct-level P(PB | context) for all three
    context variables side by side.

    Column order within each panel follows the canonical level ordering:
    ACTIVE before PASSIVE (INTENT), PRE before POST (TEMP), TR1/TR2/TR3
    (TRIGGERS).  Each panel uses a distinct colour palette so the three
    context variables are visually separable at a glance.

    Parameters
    ----------
    intent_c:
        Construct-level probability DataFrame for listening intent
        (index = construct, columns = [ACTIVE, PASSIVE]).
    temp_c:
        Construct-level probability DataFrame for temporal context
        (index = construct, columns = [PRE, POST]).
    trigger_c:
        Construct-level probability DataFrame for perceptual trigger
        (index = construct, columns = [TR1, TR2, TR3]).
    """
    fig, axes = plt.subplots(1, 3, figsize=(18, 5), sharey=True)

    PANEL_PALETTES = [
        ["#4C72B0", "#87CEEB"],             # Blues for INTENT (ACTIVE, PASSIVE)
        ["#2CA02C", "#98DF8A"],             # Greens for TEMP (PRE, POST)
        ["#D62728", "#FF9896", "#FFCC99"],  # Reds/oranges for TRIGGERS (TR1, TR2, TR3)
    ]

    # Enforce canonical column ordering before plotting
    intent_c  = intent_c.reindex(columns=["ACTIVE", "PASSIVE"])
    temp_c    = temp_c.reindex(columns=["PRE", "POST"])

    panels = [
        (intent_c,  axes[0], "P(PB | Intent)",   PANEL_PALETTES[0]),
        (temp_c,    axes[1], "P(PB | Temporal)", PANEL_PALETTES[1]),
        (trigger_c, axes[2], "P(PB | Trigger)",  PANEL_PALETTES[2]),
    ]

    for cdf, ax, title, palette in panels:
        constructs = cdf.index.tolist()
        x      = np.arange(len(constructs))
        n_cols = len(cdf.columns)
        width  = 0.8 / n_cols

        for k, col in enumerate(cdf.columns):
            offset = (k - n_cols / 2 + 0.5) * width
            color  = palette[k] if k < len(palette) else plt.cm.tab10(k / n_cols)
            ax.bar(
                x + offset,
                cdf[col].astype(float),
                width=width,
                label=str(col),
                color=color,
                alpha=0.85,
            )

        ax.set_xticks(x)
        ax.set_xticklabels(constructs, fontsize=16)
        ax.set_title(title, fontsize=16)
        ax.set_ylabel("Mean P(PB)", fontsize=16)
        ax.set_ylim(0, 0.7)
        # Fixed position and tighter rows keep the legend clear of the bars.
